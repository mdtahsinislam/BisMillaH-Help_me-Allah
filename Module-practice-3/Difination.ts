// ACCESS MODIFIERS in TypeScript
// 📘 English Definition

// Access Modifiers control
// who can access properties and methods in a class.

// They provide security and data protection.

// 📙 Bangla Definition

// Access Modifier নির্ধারণ করে
// একটি class এর property বা method
// কোথা থেকে access করা যাবে।

// এগুলো data security এবং control দেয়।




// Types of Access Modifiers

// Modifier-------Access Level
// public-----সব জায়গা থেকে access করা যায়
// private-----শুধু class এর ভিতরে
// protected------class + child class