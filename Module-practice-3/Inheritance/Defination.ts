// Inheritance (ইনহেরিটেন্স) কী?
// Definition (English) : Inheritance is an OOP (Object-Oriented Programming) feature where one class can acquire the properties and methods of another class.

// সংজ্ঞা (বাংলা) : Inheritance হলো OOP-এর এমন একটি বৈশিষ্ট্য যেখানে একটি class অন্য একটি class-এর properties এবং methods গ্রহণ করতে পারে।



// Inheritance কত প্রকার?

// সাধারণভাবে Inheritance ৫ প্রকার:

// 1)Single Inheritance
// 2)Multilevel Inheritance
// 3)Hierarchical Inheritance
// 4)Multiple Inheritance
// 5)Hybrid Inheritance




// 1. Single Inheritance
// Definition

// One child class inherits one parent class.

// বাংলা

// একটি child class একটি parent class inherit করলে তাকে Single Inheritance বলে।




// 2. Multilevel Inheritance
// Definition

// A class inherits another class, and another class inherits from it.

// বাংলা

// একটি class আরেকটি class inherit করে এবং তৃতীয় class আবার সেটিকে inherit করলে তাকে Multilevel Inheritance বলে।



// 3. Hierarchical Inheritance
// Definition

// Multiple child classes inherit one parent class.

// বাংলা


// একটি parent class কে একাধিক child class inherit করলে তাকে Hierarchical Inheritance বলে।




// 4. Multiple Inheritance
// Definition

// One child class inherits multiple parent classes.

// বাংলা

// একটি child class একাধিক parent class inherit করলে তাকে Multiple Inheritance বলে।




// 5. Hybrid Inheritance
// Definition

// Combination of two or more types of inheritance.

// বাংলা

// দুই বা ততোধিক inheritance একসাথে ব্যবহার করলে তাকে Hybrid Inheritance বলে।